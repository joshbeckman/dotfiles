// Reproduce/check the checked-in identity palette: node scripts/session-palette.js [--check]
// Glasbey-style greedy max-min sampling, not an official Glasbey or CVD-safe palette.
// See https://doi.org/10.1002/col.20327 and https://github.com/joshbeckman/notes/issues/500 for categorical vs semantic color.
import { readFileSync, writeFileSync } from 'node:fs';
import { contrast, distance, lchHex, linear, simulatedLabs, lab } from './lib/color-space.js';
const reserved = ['#002FA7', '#0D0D0D', '#FFFFFF'].map(simulatedLabs);
const separation = (a, b) => Math.min(...a.flatMap((theme, t) => theme.map((value, v) => distance(value, b[t][v]))));
const candidates = [];
for (let lightness = 36; lightness <= 60; lightness += 3) {
	for (let chroma = 4; chroma <= 24; chroma += 2) {
		for (let hue = 0; hue < 360; hue += 5) {
			// Reserve blue-like hues for the user, including near neighbors, not only its hex.
			if (hue >= 230 && hue <= 300) continue;
			const light = lchHex(lightness/100, chroma/100, hue);
			const dark = lchHex(lightness/100 + 0.28, chroma/100, hue);
			if (!light || !dark) continue;
			if (contrast(linear(light), linear('#FFFFFF')) < 4.5 || contrast(linear(dark), linear('#0D0D0D')) < 4.5) continue;
			const labs = [light, dark].map(simulatedLabs);
			if (reserved.some((r) => labs.some((theme) => theme.some((value, v) => distance(value, r[v]) < 0.10)))) continue;
			candidates.push({ light, dark, labs });
		}
	}
}
const chosen = [];
for (let i = 0; i < 12; i++) {
	let best, bestScore = -1;
	for (const candidate of candidates) {
		// Preserve normal-vision separation while optimizing the weakest simulated pair.
		if (chosen.some((used) => candidate.labs.some((theme, t) => distance(theme[0], used.labs[t][0]) < 0.08))) continue;
		const score = chosen.length ? Math.min(...chosen.map((used) => separation(candidate.labs, used.labs))) :
			Math.min(...reserved.flatMap((r) => candidate.labs.flatMap((theme) => theme.map((value, v) => distance(value, r[v])))));
		if (score > bestScore) { best = candidate; bestScore = score; }
	}
	if (!best) throw new Error('Insufficient in-gamut candidates');
	chosen.push(best);
}

// Light-mode bars are graphics, not text. Keep the approved dark palette above,
// but select much higher-chroma light accents in the same hue family.
const accents = [];
for (const [index, color] of chosen.entries()) {
	const [, a, b] = lab(linear(color.dark));
	const hue = (Math.atan2(b, a)*180/Math.PI + 360) % 360;
	let best, bestScore = -1;
	for (let lightness = 50; lightness <= 68; lightness += 3) {
		for (let chroma = 8; chroma <= 28; chroma += 2) {
			for (let offset = -30; offset <= 30; offset += 5) {
				const accentHue = (hue + offset + 360) % 360;
				if (accentHue >= 230 && accentHue <= 300) continue;
				const hex = lchHex(lightness/100, chroma/100, accentHue);
				if (!hex || contrast(linear(hex), linear('#FFFFFF')) < 3) continue;
				const labs = simulatedLabs(hex);
				if (reserved.some((r) => labs.some((value, v) => distance(value, r[v]) < 0.10))) continue;
				if (accents.some((used) => distance(labs[0], used.labs[0]) < 0.11 || labs.some((value, v) => distance(value, used.labs[v]) < 0.025))) continue;
				const score = (accents.length ? Math.min(...accents.map((used) => distance(labs[0], used.labs[0]))) : 0) + chroma/500;
				if (score > bestScore) { best = { hex, labs }; bestScore = score; }
			}
		}
	}
	if (!best) throw new Error(`No vivid accent for slot ${index + 1}`);
	accents.push(best);
}
const palette = (theme) => Object.fromEntries(chosen.map((color, i) => [`session-${i + 1}`, color[theme]]));
const dark = palette('dark');
const light = Object.fromEntries(accents.map((color, i) => [`session-${i + 1}`, color.hex]));
// A darker same-hue variant for colored links; don't force graphical accents to meet
// the text contrast threshold. Reduce chroma only when needed to stay inside sRGB.
const text = Object.fromEntries(accents.map(({ hex }, i) => {
	const [l, a, b] = lab(linear(hex));
	const hue = Math.atan2(b, a)*180/Math.PI;
	const chroma = Math.hypot(a, b);
	let best, closest = Infinity;
	for (let ll = l; ll >= 0.30; ll -= 0.01) {
		for (let cc = chroma; cc >= 0.04; cc -= 0.01) {
			const foreground = lchHex(ll, cc, hue);
			if (!foreground || contrast(linear(foreground), linear('#FFFFFF')) < 4.5) continue;
			const delta = distance(lab(linear(hex)), lab(linear(foreground)));
			if (delta < closest) { best = foreground; closest = delta; }
		}
	}
	if (!best) throw new Error(`No readable foreground for ${hex}`);
	return [`session-${i + 1}`, best];
}));
const output = `// Generated by scripts/session-palette.js; do not edit. Order is farthest-first.\nexport const SESSION_PALETTE = ${JSON.stringify(light, null, '\t')};\nexport const SESSION_DARK_PALETTE = ${JSON.stringify(dark, null, '\t')};\nexport const SESSION_TEXT_PALETTE = ${JSON.stringify(text, null, '\t')};\n`;
const cssRules = (palette, foreground, indent = '') => Object.entries(palette).map(([name, hex]) => `${indent}[data-color="${name}"] { --who: ${hex.toLowerCase()}; --who-text: ${foreground[name].toLowerCase()}; }`).join('\n');
const css = `/* BEGIN generated session palette */\n${cssRules(light, text)}\n@media (prefers-color-scheme: dark) {\n${cssRules(dark, dark, '\t')}\n}\n/* END generated session palette */`;
const stylesheet = new URL('../web/style.css', import.meta.url);
const previous = readFileSync(stylesheet, 'utf8');
if (!previous.includes('/* BEGIN generated session palette */') || !previous.includes('/* END generated session palette */')) throw new Error('Missing generated CSS markers');
const updated = previous.replace(/\/\* BEGIN generated session palette \*\/[\s\S]*?\/\* END generated session palette \*\//, css);
for (const [url, text] of [[new URL('../web/session-palette.js', import.meta.url), output], [stylesheet, updated]]) {
	if (process.argv.includes('--check')) {
		if (readFileSync(url, 'utf8') !== text) throw new Error(`Regenerate ${url.pathname}`);
	} else writeFileSync(url, text);
}
const graphics = Object.values(light).map((hex, i) => [hex, Object.values(dark)[i]].map(simulatedLabs));
console.log(`Selected 12 of ${candidates.length} base candidates; worst actual graphic OKLab pair distance ${Math.min(...graphics.flatMap((a, i) => graphics.slice(i + 1).map((b) => separation(a, b)))).toFixed(4)}. Not a universal distinguishability guarantee.`);
